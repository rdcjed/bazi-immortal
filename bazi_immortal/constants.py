# ─── 十神 ───
# 日干五行 → 其他天干五行 → 十神
def get_shi_shen(ri_gan: str, other_gan: str) -> str:
    """根据日干和其他天干，返回十神名称"""
    if ri_gan == other_gan:
        return "比肩" if TG_YIN_YANG[ri_gan] == TG_YIN_YANG[other_gan] else "劫财"

    ri_wx = TG_WU_XING[ri_gan]
    other_wx = TG_WU_XING[other_gan]

    # 生我者为印枭
    if WU_XING_SHENG.get(other_wx) == ri_wx:
        return "正印" if TG_YIN_YANG[ri_gan] != TG_YIN_YANG[other_gan] else "偏印"
    # 我生者为食伤
    if WU_XING_SHENG.get(ri_wx) == other_wx:
        return "食神" if TG_YIN_YANG[ri_gan] == TG_YIN_YANG[other_gan] else "伤官"
    # 克我者为官杀
    if WU_XING_KE.get(other_wx) == ri_wx:
        return "正官" if TG_YIN_YANG[ri_gan] != TG_YIN_YANG[other_gan] else "七杀"
    # 我克者为财
    if WU_XING_KE.get(ri_wx) == other_wx:
        return "正财" if TG_YIN_YANG[ri_gan] == TG_YIN_YANG[other_gan] else "偏财"

    return "比肩"  # fallback

