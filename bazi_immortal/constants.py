# 天干+地支组合 → 六十甲子中的序号
def gan_zhi_to_index(tg: str, dz: str) -> int:
    """天干地支 → 六十甲子序号"""
    tg_i = TG_INDEX[tg]
    dz_i = DZ_INDEX[dz]
    for i, (t, d) in enumerate(LIU_SHI_JIA_ZI):
        if t == tg_i and d == dz_i:
            return i
    raise ValueError(f"无效干支组合: {tg}{dz}")

