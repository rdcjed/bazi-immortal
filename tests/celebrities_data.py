# 验证函数
def validate_celebrity_data():
    """验证数据完整性"""
    errors = []
    seen = {}
    for i, entry in enumerate(CELEBRITIES):
        name = entry[0]
        year = entry[1]
        if year < 1850 or year > 2010:
            errors.append(f"[{i}] {name}: 年份{year}超出合理范围")
        if name in seen:
            errors.append(f"[{i}] {name}: 与[{seen[name]}]重复")
        seen[name] = i
    return errors


