def validate_verified_data():
    """验证数据完整性"""
    errors = []
    seen = set()
    for i, entry in enumerate(VERIFIED_CELEBRITIES):
        name = entry[0]
        if name in seen:
            errors.append(f"[{i}] {name}: 重复")
        seen.add(name)
    return errors


